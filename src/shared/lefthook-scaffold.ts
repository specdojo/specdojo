import { existsSync } from "node:fs";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { SpecDojoConfig } from "./specdojo-config.js";

const REQUIRED_DEV_DEPENDENCIES = ["lefthook", "prettier", "markdownlint-cli"] as const;

const REQUIRED_SCRIPTS = {
  prepare: "node tools/install-lefthook.mjs",
  "pre-commit": "lefthook run pre-commit",
} as const;

type JsonObject = Record<string, unknown>;

export interface RunLefthookScaffoldOptions {
  packageRoot: string;
  repoRoot: string;
  config: SpecDojoConfig;
  force: boolean;
  dryRun: boolean;
}

function isRecord(value: unknown): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function hasConfiguredPath(
  config: SpecDojoConfig,
  key: "project_register_path" | "catalog_path",
): boolean {
  return Object.values(config.projects).some((project) => !!project[key]?.trim());
}

export function renderLefthookConfig(config: SpecDojoConfig): string {
  const commands = [
    "    prettier:",
    '      glob: "*.{md,yaml,yml}"',
    "      run: node tools/specdojo-pre-commit.mjs prettier {staged_files}",
    "      stage_fixed: true",
    "",
    "    markdownlint:",
    '      glob: "*.md"',
    "      run: node tools/specdojo-pre-commit.mjs markdownlint {staged_files}",
  ];

  if (hasConfiguredPath(config, "project_register_path")) {
    commands.push(
      "",
      "    register-build:",
      "      run: node tools/specdojo-pre-commit.mjs register-build",
      "      stage_fixed: true",
    );
  }
  if (hasConfiguredPath(config, "catalog_path")) {
    commands.push(
      "",
      "    catalog-validate:",
      "      run: node tools/specdojo-pre-commit.mjs catalog-validate",
    );
  }

  return [
    "# Generated by SpecDojo. Re-run `specdojo config scaffold --lefthook --force` to refresh.",
    "pre-commit:",
    "  parallel: false",
    "  commands:",
    ...commands,
    "",
  ].join("\n");
}

function detectIndent(content: string): string | number {
  const match = content.match(/^([\t ]+)\S/m);
  if (!match) return 2;
  return match[1].includes("\t") ? "\t" : match[1].length;
}

function parsePackageJson(content: string, packageJsonPath: string): JsonObject {
  let value: unknown;
  try {
    value = JSON.parse(content);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new Error(`Invalid JSON in ${packageJsonPath}: ${message}`);
  }
  if (!isRecord(value)) throw new Error(`Invalid JSON in ${packageJsonPath}: expected an object`);
  return value;
}

async function requiredDependencyVersions(packageRoot: string): Promise<Record<string, string>> {
  const sourcePath = path.join(packageRoot, "package.json");
  const source = parsePackageJson(await readFile(sourcePath, "utf8"), sourcePath);
  // prettier is a runtime dependency of SpecDojo itself, so versions are resolved from both fields.
  const dependencies = {
    ...(isRecord(source.dependencies) ? source.dependencies : {}),
    ...(isRecord(source.devDependencies) ? source.devDependencies : {}),
  };
  return Object.fromEntries(
    REQUIRED_DEV_DEPENDENCIES.map((name) => {
      const version = dependencies[name];
      if (typeof version !== "string") {
        throw new Error(
          `SpecDojo package.json (${sourcePath}) does not declare dependency or devDependency: ${name}`,
        );
      }
      return [name, version];
    }),
  );
}

async function updatePackageJson(opts: RunLefthookScaffoldOptions): Promise<void> {
  const packageJsonPath = path.join(opts.repoRoot, "package.json");
  const requiredDependencies = await requiredDependencyVersions(opts.packageRoot);
  if (!existsSync(packageJsonPath)) {
    process.stdout.write(
      "Skipped package.json update (package.json not found). Add these entries after creating it:\n" +
        `${JSON.stringify({ scripts: REQUIRED_SCRIPTS, devDependencies: requiredDependencies }, null, 2)}\n`,
    );
    return;
  }

  const content = await readFile(packageJsonPath, "utf8");
  const packageJson = parsePackageJson(content, packageJsonPath);
  if (packageJson.scripts !== undefined && !isRecord(packageJson.scripts)) {
    throw new Error(`Invalid ${packageJsonPath}: scripts must be an object`);
  }
  if (packageJson.dependencies !== undefined && !isRecord(packageJson.dependencies)) {
    throw new Error(`Invalid ${packageJsonPath}: dependencies must be an object`);
  }
  if (packageJson.devDependencies !== undefined && !isRecord(packageJson.devDependencies)) {
    throw new Error(`Invalid ${packageJsonPath}: devDependencies must be an object`);
  }

  const scripts = isRecord(packageJson.scripts) ? packageJson.scripts : {};
  const dependencies = isRecord(packageJson.dependencies) ? packageJson.dependencies : {};
  const devDependencies = isRecord(packageJson.devDependencies) ? packageJson.devDependencies : {};
  const scriptAdditions = Object.fromEntries(
    Object.entries(REQUIRED_SCRIPTS).filter(([name]) => !Object.hasOwn(scripts, name)),
  );
  const dependencyAdditions = Object.fromEntries(
    Object.entries(requiredDependencies).filter(
      ([name]) => !Object.hasOwn(dependencies, name) && !Object.hasOwn(devDependencies, name),
    ),
  );
  const additions = { scripts: scriptAdditions, devDependencies: dependencyAdditions };

  process.stdout.write(`Planned package.json additions:\n${JSON.stringify(additions, null, 2)}\n`);
  for (const name of Object.keys(REQUIRED_SCRIPTS)) {
    if (Object.hasOwn(scripts, name)) {
      process.stdout.write(`Skipped (script already exists): ${name} in package.json\n`);
    }
  }
  for (const name of REQUIRED_DEV_DEPENDENCIES) {
    if (Object.hasOwn(dependencies, name) || Object.hasOwn(devDependencies, name)) {
      process.stdout.write(`Skipped (dependency already exists): ${name} in package.json\n`);
    }
  }

  if (
    opts.dryRun ||
    (Object.keys(scriptAdditions).length === 0 && Object.keys(dependencyAdditions).length === 0)
  ) {
    return;
  }
  packageJson.scripts = { ...scripts, ...scriptAdditions };
  packageJson.devDependencies = { ...devDependencies, ...dependencyAdditions };
  await writeFile(
    packageJsonPath,
    `${JSON.stringify(packageJson, null, detectIndent(content))}\n`,
    "utf8",
  );
  process.stdout.write("Updated: package.json\n");
}

async function writeScaffoldFile(
  sourcePath: string | undefined,
  destinationPath: string,
  destinationLabel: string,
  content: string | undefined,
  opts: Pick<RunLefthookScaffoldOptions, "force" | "dryRun">,
): Promise<void> {
  if (existsSync(destinationPath) && !opts.force) {
    process.stdout.write(`Skipped (already exists): ${destinationLabel}\n`);
    return;
  }
  if (opts.dryRun) {
    process.stdout.write(`[dry-run] would write: ${destinationLabel}\n`);
    return;
  }
  await mkdir(path.dirname(destinationPath), { recursive: true });
  if (sourcePath) await copyFile(sourcePath, destinationPath);
  else await writeFile(destinationPath, content ?? "", "utf8");
  process.stdout.write(`Written: ${destinationLabel}\n`);
}

export async function runLefthookScaffold(opts: RunLefthookScaffoldOptions): Promise<void> {
  const templateTools = path.join(opts.packageRoot, "templates", "lefthook", "tools");
  await writeScaffoldFile(
    undefined,
    path.join(opts.repoRoot, "lefthook.yml"),
    "lefthook.yml",
    renderLefthookConfig(opts.config),
    opts,
  );
  for (const filename of ["install-lefthook.mjs", "specdojo-pre-commit.mjs"]) {
    await writeScaffoldFile(
      path.join(templateTools, filename),
      path.join(opts.repoRoot, "tools", filename),
      `tools/${filename}`,
      undefined,
      opts,
    );
  }
  await updatePackageJson(opts);
  if (!opts.dryRun) {
    process.stdout.write(
      "Next steps:\n" +
        "  1. Run npm install and review the package.json additions shown above.\n" +
        "  2. Run node tools/install-lefthook.mjs if an existing prepare script was kept.\n" +
        "  3. Stage and commit lefthook.yml, tools/, and package.json.\n",
    );
  }
}
